/**
 * The DES permutation and substitution tables, transcribed from FIPS PUB 46-3
 * (Data Encryption Standard), Appendix — "Primitive functions for the Data
 * Encryption Algorithm".
 *
 * FIPS 46-3 was WITHDRAWN by NIST on 2005-05-19. It is reproduced here as a
 * historical specification, not as a live standard. The withdrawal dates for
 * every document this lab cites are in `vectors.ts` and in the README's
 * "What It Is".
 *
 * Every table below indexes bits the way the standard does: bit 1 is the
 * most-significant bit of the first byte, bit 64 the least-significant bit of
 * the eighth. `permute()` in `des.ts` is the only place that translates that
 * numbering into JavaScript, so these arrays can be read straight against the
 * printed tables in the standard.
 *
 * Nothing here is derived, inferred or generated. A single transposed digit in
 * any of these tables produces a cipher that still round-trips perfectly and
 * still looks random — which is exactly why the CAVP known-answer vectors in
 * `vectors.ts` are the gate on this file rather than a round-trip test.
 */

